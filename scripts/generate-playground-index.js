/**
 * Generates an interactive Component Playground catalog index.
 * Outputs:
 *   - public/playground.html (Interactive live preview environment)
 *   - src/components/playground.generated.js (Module data export)
 */
const fs = require('fs');
const path = require('path');

const componentsDir = path.resolve(__dirname, '..', 'src', 'components');
const htmlOutput = path.resolve(__dirname, '..', 'public', 'playground.html');
const jsOutput = path.resolve(componentsDir, 'playground.generated.js');

function findComponents(dir) {
  if (!fs.existsSync(dir)) return [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const components = [];

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith('_')) continue;
    const compDir = path.join(dir, entry.name);
    const metaPath = path.join(compDir, 'metadata.js');
    const examplesPath = path.join(compDir, 'examples.js');

    if (fs.existsSync(metaPath)) {
      try {
        const metaModule = require(metaPath);
        const metadata = metaModule.metadata || metaModule;
        let examples = [];
        if (fs.existsSync(examplesPath)) {
          try {
            const exModule = require(examplesPath);
            examples = exModule.examples || exModule || [];
          } catch (_) {}
        }
        components.push({
          name: entry.name,
          metadata,
          examples
        });
      } catch (err) {
        console.warn(`Could not load component ${entry.name}:`, err.message);
      }
    }
  }
  return components;
}

const components = findComponents(componentsDir);

// 1. Generate JS module export
const jsContent = `// THIS FILE IS AUTO-GENERATED BY scripts/generate-playground-index.js
// DO NOT EDIT MANUALLY

export const playgroundCatalog = ${JSON.stringify(components, null, 2)};
`;
fs.writeFileSync(jsOutput, jsContent, 'utf8');

