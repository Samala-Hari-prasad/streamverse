// scripts/generate-components-css.js

/**
 * Generates an aggregated CSS file that imports component CSS files in dependency order.
 * Output: src/assets/css/components.generated.css
 *
 * Dependency ordering:
 *   1. Primitives (Spinner, Skeleton, Badge, Avatar, Icon)
 *   2. Interactive Elements (Button, IconButton, Chip)
 *   3. Form Inputs (Input, SearchInput)
 *   4. Surfaces & Containers (Card, Modal, Drawer, Toast, Tooltip)
 *   5. Navigation & Layout (Sidebar, Header, Hero, ContentRail)
 *   6. Composite Views & Complex Components
 */
const fs = require('fs');
const path = require('path');

const componentsDir = path.resolve(__dirname, '..', 'src', 'components');
const assetsCssDir = path.resolve(__dirname, '..', 'src', 'assets', 'css');
const outputPath = path.resolve(assetsCssDir, 'components.generated.css');

const CATEGORY_WEIGHTS = {
  primitives: 10,
  elements: 20,
  actions: 20,
  buttons: 20,
  inputs: 30,
  forms: 30,
  feedback: 40,
  surfaces: 40,
  containers: 40,
  navigation: 50,
  layout: 50,
  composite: 60,
  views: 70
};

const COMPONENT_DEFAULT_WEIGHTS = {
  spinner: 10,
  skeleton: 11,
  badge: 12,
  avatar: 13,
  icon: 14,
  button: 20,
  iconbutton: 21,
  chip: 22,
  input: 30,
  searchinput: 31,
  card: 40,
  modal: 41,
  drawer: 42,
  toast: 43,
  tooltip: 44,
  sidebar: 50,
  navbar: 51,
  header: 52,
  hero: 53,
  rail: 54
};

function getComponentInfo(compDir) {
  const metaPath = path.join(compDir, 'metadata.js');
  let meta = {};
  if (fs.existsSync(metaPath)) {
    try {
      const loaded = require(metaPath);
      meta = loaded.metadata || loaded;
    } catch (_) {}
  }
  return meta;
}

function collectComponentCss(dir) {
  if (!fs.existsSync(dir)) return [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const components = [];

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith('_')) continue;
    const compDir = path.join(dir, entry.name);
    const meta = getComponentInfo(compDir);
    const compName = entry.name;
    const lowerName = compName.toLowerCase();

    // Look for component CSS file
    const cssFile = path.join(compDir, `${compName}.css`);
    if (fs.existsSync(cssFile)) {
      const relPath = path.relative(assetsCssDir, cssFile).replace(/\\/g, '/');
      const cat = (meta.category || '').toLowerCase();
      let weight = CATEGORY_WEIGHTS[cat] || COMPONENT_DEFAULT_WEIGHTS[lowerName] || 50;

      components.push({
        name: compName,
        relPath,
        dependencies: Array.isArray(meta.dependencies) ? meta.dependencies : [],
        weight
      });
    }
  }

  // Sort components by dependency weight, then resolve topological constraints
  components.sort((a, b) => {
    if (a.dependencies.includes(b.name)) return 1;
    if (b.dependencies.includes(a.name)) return -1;
    if (a.weight !== b.weight) return a.weight - b.weight;
    return a.name.localeCompare(b.name);
  });

  return components;
}

const components = collectComponentCss(componentsDir);

let content = `/* THIS FILE IS AUTO-GENERATED BY scripts/generate-components-css.js */\n`;
content += `/* DO NOT EDIT MANUALLY - Styles are ordered by dependency hierarchy */\n\n`;

if (components.length === 0) {
  content += `/* No component styles registered yet */\n`;
} else {
  components.forEach((c) => {
    content += `@import "${c.relPath}"; /* ${c.name} (weight: ${c.weight}) */\n`;
  });
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, content, { encoding: 'utf8' });
console.log(`Components CSS generated with dependency ordering (${components.length} components) at:`, outputPath);
